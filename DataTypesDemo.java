public class DataTypesDemo {
    public static void main(String[] args) {

        int countValue = 100;
        float floatValue = 12.5f;
        double decimalValue = 99.99;
        char gradeValue = 'A';
        boolean activeFlag = true;

        System.out.println("Int = " + countValue);
        System.out.println("Float = " + floatValue);
        System.out.println("Double = " + decimalValue);
        System.out.println("Char = " + gradeValue);
        System.out.println("Boolean = " + activeFlag);
    }
}
